-- Clarity-shaped SQL mirroring the Python night extract window.
-- Watermark: 2024-11-12 01:00 to 05:00

WITH enc AS (
  SELECT *
  FROM PAT_ENC
  WHERE (HOSP_ADMSN_TIME >= TIMESTAMP '2024-11-12 01:00:00'
         AND HOSP_ADMSN_TIME <  TIMESTAMP '2024-11-12 05:00:00')
     OR (HOSP_ADMSN_TIME < TIMESTAMP '2024-11-12 05:00:00'
         AND (HOSP_DISCH_TIME IS NULL
              OR HOSP_DISCH_TIME >= TIMESTAMP '2024-11-12 01:00:00'))
),
res AS (
  SELECT r.*, op.PAT_ENC_CSN_ID, e.PAT_ID
  FROM ORDER_RESULTS r
  JOIN ORDER_PROC op ON op.ORDER_PROC_ID = r.ORDER_PROC_ID
  JOIN PAT_ENC e ON e.PAT_ENC_CSN_ID = op.PAT_ENC_CSN_ID
  WHERE r.RESULT_TIME >= TIMESTAMP '2024-11-12 01:00:00'
    AND r.RESULT_TIME <  TIMESTAMP '2024-11-12 05:00:00'
)
SELECT * FROM res
WHERE PAT_ID IN (SELECT PAT_ID FROM PATIENT);
